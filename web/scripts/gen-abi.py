"""Writes web/src/lib/frontline/abi.ts from Foundry build output (contracts/out).
Run after `forge build`:  python web/scripts/gen-abi.py"""
import json, pathlib, sys

root = pathlib.Path(__file__).resolve().parents[2]
out = root / "contracts" / "out"
names = ["AbsorberVault", "ProtectedLoanFactory", "ProtectedLoan", "FrontlineLens"]
lines = ["// Generated by web/scripts/gen-abi.py from contracts/out. Do not edit by hand.", ""]
for n in names:
    abi = json.loads((out / f"{n}.sol" / f"{n}.json").read_text(encoding="utf-8"))["abi"]
    lines.append(f"export const {n[0].lower() + n[1:]}Abi = {json.dumps(abi, indent=2)} as const;")
    lines.append("")
target = root / "web" / "src" / "lib" / "frontline" / "abi.ts"
target.write_text("\n".join(lines), encoding="utf-8")
print("wrote", target, sum(1 for _ in lines))
